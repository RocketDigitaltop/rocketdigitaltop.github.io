// Update contact form colors based on theme
function updateFormTheme() {
  const alternateLink = document.querySelector('link[title="alternate"]');
  const isLightMode = alternateLink && !alternateLink.disabled;
  const body = document.body;
  
  if (isLightMode) {
    body.classList.add('light-theme');
    body.classList.remove('dark-theme');
  } else {
    body.classList.add('dark-theme');
    body.classList.remove('light-theme');
  }
}

// Run on page load
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', updateFormTheme);
} else {
  updateFormTheme();
}

// Watch for theme changes (monitor stylesheet changes)
const observer = new MutationObserver(function(mutations) {
  mutations.forEach(function(mutation) {
    if (mutation.type === 'attributes' && mutation.attributeName === 'disabled') {
      updateFormTheme();
    }
  });
});

// Observe the alternate stylesheet link
const alternateLink = document.querySelector('link[title="alternate"]');
if (alternateLink) {
  observer.observe(alternateLink, { attributes: true });
}

// Also check periodically (fallback)
setInterval(updateFormTheme, 500);
